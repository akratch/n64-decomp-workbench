"""Profiled instrumentation for statically recompiled IDO 5.3 uopt.

The generated C file is not a stable API: function labels and emulated-memory
addresses are tied to the input executable and static-recompiler revision.
This module therefore supports a pinned profile and refuses unknown source by
default instead of pretending the patch is portable across IDO releases.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass

MARKER = "DKWB_UOPT_GLOBALCOLOR_V1"
IDO_53_V12_SHA256 = "b0058f1559441c1a194d649271eb43b8637ec255682cfdd629031340b915b13f"

HEADER = r"""
/* DKWB_UOPT_GLOBALCOLOR_V1
 * Generated by n64-decomp-workbench for the pinned IDO 5.3 static-recomp
 * profile. Tracing is opt-in with CDX_LOG; CDX_FORCE is a diagnostic oracle.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static int dkwb_cdx_ready;
static int dkwb_cdx_log;
static int dkwb_cdx_proc = -1;
static int dkwb_cdx_globalcolor_ordinal = -1;
static char dkwb_cdx_force[16384];
static FILE *dkwb_cdx_output;
static void dkwb_cdx_init(void) {
    const char *value;
    if (dkwb_cdx_ready) return;
    dkwb_cdx_ready = 1;
    value = getenv("CDX_LOG");
    dkwb_cdx_log = value ? atoi(value) : 0;
    value = getenv("CDX_PROC");
    dkwb_cdx_proc = value ? atoi(value) : -1;
    value = getenv("CDX_FORCE");
    if (value) {
        strncpy(dkwb_cdx_force, value, sizeof(dkwb_cdx_force) - 1);
        dkwb_cdx_force[sizeof(dkwb_cdx_force) - 1] = '\0';
    }
    value = getenv("CDX_OUT");
    dkwb_cdx_output = value && *value ? fopen(value, "w") : stderr;
    if (!dkwb_cdx_output) dkwb_cdx_output = stderr;
    if (dkwb_cdx_force[0] && dkwb_cdx_proc < 0) {
        fprintf(stderr, "DKWB: CDX_FORCE ignored without CDX_PROC\n");
        dkwb_cdx_force[0] = '\0';
    }
}
static int dkwb_cdx_active(int ordinal) {
    return dkwb_cdx_proc < 0 || ordinal == dkwb_cdx_proc;
}
/* -2: no override, -1: force split/no-color, >=0: force color. */
static int dkwb_cdx_lookup(int ordinal, int web) {
    char key[32];
    const char *cursor;
    int key_length;
    if (!dkwb_cdx_force[0] || !dkwb_cdx_active(ordinal)) return -2;
    key_length = snprintf(key, sizeof(key), "w%d=", web);
    cursor = dkwb_cdx_force;
    while ((cursor = strstr(cursor, key)) != NULL) {
        if (cursor == dkwb_cdx_force || cursor[-1] == ',') {
            const char *value = cursor + key_length;
            if (*value == 's') return -1;
            if (*value == 'c') return atoi(value + 1);
        }
        cursor += key_length;
    }
    return -2;
}
#define DKWB_CDX_LOG(ordinal, ...) do { \
    if (dkwb_cdx_log && dkwb_cdx_active(ordinal)) \
        fprintf(dkwb_cdx_output, __VA_ARGS__); \
} while (0)
"""


@dataclass(frozen=True)
class UoptInstrumentationResult:
    """Instrumented source plus the profile identity."""

    source: str
    input_sha256: str
    profile: str = "ido-5.3-static-recomp-v12"
    trace_points: int = 6


def _replace_once(source: str, old: str, new: str, label: str) -> str:
    count = source.count(old)
    if count != 1:
        raise ValueError(
            f"uopt profile anchor {label!r} occurred {count} times; "
            "the generated source does not match this instrumentation profile"
        )
    return source.replace(old, new, 1)


def instrument_uopt_globalcolor(
    source: str, *, allow_unverified_source: bool = False
) -> UoptInstrumentationResult:
    """Add trace and force-choice hooks to the pinned uopt generated C."""

    if MARKER in source:
        raise ValueError("source is already instrumented")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    if not allow_unverified_source and digest != IDO_53_V12_SHA256:
        raise ValueError(
            "source SHA-256 is not the pinned IDO 5.3 static-recomp profile "
            f"({digest}); pass --allow-unverified-source only after reviewing "
            "every anchor and running a disabled-instrumentation fidelity test"
        )

    result = _replace_once(
        source,
        "static void f_compute_save(uint8_t *mem, uint32_t sp, uint32_t a0) {\n",
        HEADER
        + "\nstatic void f_compute_save(uint8_t *mem, uint32_t sp, uint32_t a0) {\n",
        "instrumentation header",
    )
    result = _replace_once(
        result,
        "uint32_t a3 = 0;\nL47106c:\n//globalcolor:",
        "uint32_t a3 = 0;\n"
        "int dkwb_cdx_ordinal;\n"
        "int dkwb_cdx_decision;\n"
        "dkwb_cdx_init();\n"
        "dkwb_cdx_globalcolor_ordinal++;\n"
        "dkwb_cdx_ordinal = dkwb_cdx_globalcolor_ordinal;\n"
        'DKWB_CDX_LOG(dkwb_cdx_ordinal, "[CDX] globalcolor proc=%d\\n", '
        "dkwb_cdx_ordinal);\n"
        "L47106c:\n//globalcolor:",
        "globalcolor entry",
    )
    result = _replace_once(
        result,
        "L471758:\ns5 = MEM_U32(sp + 276);\n//nop;\nf0.w[0] = MEM_U32(s5 + 48);",
        "L471758:\ns5 = MEM_U32(sp + 276);\n//nop;\n"
        "f0.w[0] = MEM_U32(s5 + 48);\n"
        "DKWB_CDX_LOG(dkwb_cdx_ordinal, "
        '"[CDX] p1cand proc=%d web=%d sym=%d save=%.6f '
        'nocs=%d best=%.6f\\n", dkwb_cdx_ordinal, '
        "(int)MEM_U32(sp + 272), "
        "(int)MEM_U16(MEM_U32(s5 + 0) + 2), (double)f0.f[0], "
        "(int)MEM_U32(s5 + 28), (double)f20.f[0]);",
        "phase-one candidate",
    )
    # Phase one compares all ranges, then keeps the selected bit position at
    # sp+268 for the decision and color sites below.
    result = _replace_once(
        result,
        "cf = f6.f[0] <= f20.f[0];\n//nop;\nif (!cf) {",
        "cf = f6.f[0] <= f20.f[0];\n"
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + 268);\n"
        "    dkwb_cdx_decision = dkwb_cdx_lookup("
        "dkwb_cdx_ordinal, dkwb_web);\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, "
        '"[CDX] p1dec proc=%d web=%d sym=%d class=%d save=%.6f '
        "nocs=%d totalsave=%.6f bestcost=%.6f bestcolor=%d "
        'decision=%s forced=%d\\n", dkwb_cdx_ordinal, dkwb_web, '
        "(int)MEM_U16(MEM_U32(s5 + 0) + 2), (int)s6, "
        "(double)f10.f[0], (int)t2, (double)f6.f[0], "
        "(double)f20.f[0], (int)MEM_U32(sp + 220), "
        'cf ? "split" : "color", dkwb_cdx_decision);\n'
        "    if (dkwb_cdx_decision == -1) cf = 1;\n"
        "    else if (dkwb_cdx_decision >= 0) cf = 0;\n"
        "}\n"
        "//nop;\nif (!cf) {",
        "phase-one decision",
    )
    result = _replace_once(
        result,
        "L471d6c:\nt5 = MEM_U32(sp + 220);",
        "L471d6c:\n"
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + 268);\n"
        "    int dkwb_force = dkwb_cdx_lookup("
        "dkwb_cdx_ordinal, dkwb_web);\n"
        "    if (dkwb_force >= 0) {\n"
        "        MEM_U32(sp + 220) = (uint32_t)dkwb_force;\n"
        "        t8 = (uint32_t)dkwb_force;\n"
        "    }\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, "
        '"[CDX] p1color proc=%d web=%d sym=%d color=%d forced=%d\\n", '
        "dkwb_cdx_ordinal, dkwb_web, "
        "(int)MEM_U16(MEM_U32(s5 + 0) + 2), "
        "(int)MEM_U32(sp + 220), dkwb_force);\n"
        "}\n"
        "t5 = MEM_U32(sp + 220);",
        "phase-one color",
    )
    # Phase two walks ranges directly; its current bit position is sp+272.
    result = _replace_once(
        result,
        "cf = f20.f[0] < f10.f[0];\n//nop;\nif (!cf) {",
        "cf = f20.f[0] < f10.f[0];\n"
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + 272);\n"
        "    dkwb_cdx_decision = dkwb_cdx_lookup("
        "dkwb_cdx_ordinal, dkwb_web);\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, "
        '"[CDX] p2dec proc=%d web=%d sym=%d class=%d save=%.6f '
        "nocs=%d totalsave=%.6f bestcost=%.6f bestcolor=%d "
        'decision=%s forced=%d\\n", dkwb_cdx_ordinal, dkwb_web, '
        "(int)MEM_U16(MEM_U32(s5 + 0) + 2), (int)s6, "
        "(double)f8.f[0], (int)t0, (double)f10.f[0], "
        "(double)f20.f[0], (int)MEM_U32(sp + 220), "
        'cf ? "color" : "no-color", dkwb_cdx_decision);\n'
        "    if (dkwb_cdx_decision == -1) cf = 0;\n"
        "    else if (dkwb_cdx_decision >= 0) cf = 1;\n"
        "}\n"
        "//nop;\nif (!cf) {",
        "phase-two decision",
    )
    result = _replace_once(
        result,
        "L4727d4:\nt8 = MEM_U32(sp + 220);",
        "L4727d4:\n"
        "{\n"
        "    int dkwb_web = (int)MEM_U32(sp + 272);\n"
        "    int dkwb_force = dkwb_cdx_lookup("
        "dkwb_cdx_ordinal, dkwb_web);\n"
        "    if (dkwb_force >= 0) {\n"
        "        MEM_U32(sp + 220) = (uint32_t)dkwb_force;\n"
        "        t0 = (uint32_t)dkwb_force;\n"
        "    }\n"
        "    DKWB_CDX_LOG(dkwb_cdx_ordinal, "
        '"[CDX] p2color proc=%d web=%d sym=%d color=%d forced=%d\\n", '
        "dkwb_cdx_ordinal, dkwb_web, "
        "(int)MEM_U16(MEM_U32(s5 + 0) + 2), "
        "(int)MEM_U32(sp + 220), dkwb_force);\n"
        "}\n"
        "t8 = MEM_U32(sp + 220);",
        "phase-two color",
    )
    return UoptInstrumentationResult(
        source=result,
        input_sha256=digest,
    )
