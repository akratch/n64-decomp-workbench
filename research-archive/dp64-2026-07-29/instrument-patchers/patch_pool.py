DEF_RE_TMPL = (
    r"^static (?P<ret>[A-Za-z_][A-Za-z0-9_ ]*?) (?P<name>@NAME@)"
    r"\((?P<args>uint8_t \*mem, uint32_t sp[^;\n)]*)\) \{$"
)

ARG_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*$")


def build_wrapper(ret, name, args, entry, exit_):
    names = [ARG_RE.search(a.strip()).group(1) for a in args.split(",")]
    call = ", ".join(names)
    real = name + "__dkwbreal"
    # Unused-parameter suppression for hooks that ignore some args.
    voids = "".join("    (void) %s;\n" % n for n in names)
    out = []
    out.append("static %s %s(%s);" % (ret, real, args))
    out.append("static %s %s(%s) {" % (ret, name, args))
    out.append(voids.rstrip("\n"))
    if ret != "void":
        out.append("    %s __dkwb_r;" % ret)
    out.append("    dkwb_pool_depth++;")
    if entry:
        out.append("    " + entry.replace("\n", "\n    "))
    if ret != "void":
        out.append("    __dkwb_r = %s(%s);" % (real, call))
    else:
        out.append("    %s(%s);" % (real, call))
    if exit_:
        out.append("    " + exit_.replace("\n", "\n    "))
    out.append("    dkwb_pool_depth--;")
    if ret != "void":
        out.append("    return __dkwb_r;")
    out.append("}")
    out.append("static %s %s(%s) {" % (ret, real, args))
    return "\n".join(out)


def helper_offset(src):
    m = list(re.finditer(r"^\s*#include[^\n]*\n", src, re.MULTILINE))
    return m[-1].end() if m else 0


def main():
    src = open(sys.argv[1]).read()
    if MARKER in src:
        raise SystemExit("already instrumented")

    applied, missing = [], []
    for name, (_evname, entry, exit_) in HOOKS.items():
        rx = re.compile(
            DEF_RE_TMPL.replace("@NAME@", re.escape(name)), re.MULTILINE
        )
        m = rx.search(src)
        if not m:
            missing.append(name)
            continue
        wrapper = build_wrapper(
            m.group("ret"), name, m.group("args"), entry, exit_
        )
        src = src[: m.start()] + wrapper + src[m.end():]
        applied.append(name)

    off = helper_offset(src)
    src = src[:off] + HELPERS + src[off:]
    open(sys.argv[2], "w").write(src)
    print("wrapped %d: %s" % (len(applied), " ".join(sorted(applied))))
    if missing:
        print("MISSING %d: %s" % (len(missing), " ".join(sorted(missing))))


if __name__ == "__main__":
    main()
