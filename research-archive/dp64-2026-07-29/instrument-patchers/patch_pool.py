#!/usr/bin/env python3
"""DKWB_UGEN_POOL_V1 - local-register-allocator pool instrumentation for
statically recompiled IDO 5.3 ugen.

Wraps the ugen local allocator entry points so every pool get / put is logged
together with a full snapshot of the free list and the busy (LRU) list.

Everything is gated on DKWB_UGEN_POOL; with the variable unset the helpers
return immediately and no emulated state is touched, so ugen output must stay
byte-identical to stock.

usage: patch_pool.py IN.c OUT.c
"""
import re
import sys

MARKER = "DKWB_UGEN_POOL_V1"

# ---------------------------------------------------------------- helpers ---
# Emulated globals, established by reading the recompiled allocator:
#   0x10019830  register table, 12 bytes/entry
#                 +4 u16 usage count
#                 +6 u8  next-in-list link
#                 +7 u8  "on free list" flag
#                 +8 u8  kind (6/7 == half of a double-register pair)
#                 +9 u8  paired register
#   0x10019da4  GP free list   {u8 head, u8 tail}   (f_add_to_free_list target)
#   0x10019da8  GP busy list   {u8 head, u8 tail}   (LRU, spill victim at head)
#   0x48 (72)   NIL register sentinel
HELPERS = r"""
/* DKWB_UGEN_POOL_V1
 * Generated by ugen_deepdive/patch_pool.py.
 * Inert unless DKWB_UGEN_POOL is set in the environment.
 */
#include <stdio.h>
#include <stdlib.h>

#define DKWB_REGTAB   0x10019830u
#define DKWB_FREELIST 0x10019da4u
#define DKWB_BUSYLIST 0x10019da8u
#define DKWB_NILREG   0x48u

static int dkwb_pool_state = -1;
static int dkwb_pool_proc_filter = -1;
static int dkwb_pool_proc = -1;
static unsigned long dkwb_pool_seq = 0;
static int dkwb_pool_depth = 0;
static int dkwb_pool_insn = 0;
static int dkwb_pool_gets = 0;
static FILE *dkwb_pool_fp = NULL;

static const char *dkwb_regname(unsigned r) {
    static const char *n[32] = {
        "zero","at","v0","v1","a0","a1","a2","a3",
        "t0","t1","t2","t3","t4","t5","t6","t7",
        "s0","s1","s2","s3","s4","s5","s6","s7",
        "t8","t9","k0","k1","gp","sp","s8","ra"};
    if (r == DKWB_NILREG) return "NIL";
    if (r < 32) return n[r];
    return "?";
}

static int dkwb_pool_on(void) {
    if (dkwb_pool_state < 0) {
        const char *v = getenv("DKWB_UGEN_POOL");
        const char *p = getenv("DKWB_UGEN_POOL_PROC");
        const char *o = getenv("DKWB_UGEN_POOL_OUT");
        dkwb_pool_state = v != NULL && *v != '\0' && *v != '0';
        if (p != NULL && *p != '\0') dkwb_pool_proc_filter = atoi(p);
        dkwb_pool_fp = stderr;
        if (dkwb_pool_state && o != NULL && *o != '\0') {
            FILE *f = fopen(o, "w");
            if (f != NULL) dkwb_pool_fp = f;
        }
    }
    return dkwb_pool_state;
}

/* true when the current procedure passes DKWB_UGEN_POOL_PROC */
static int dkwb_sel(void) {
    if (!dkwb_pool_on()) return 0;
    if (dkwb_pool_proc_filter < 0) return 1;
    return dkwb_pool_proc == dkwb_pool_proc_filter;
}

static void dkwb_pfx(const char *ev) {
    fprintf(dkwb_pool_fp, "POOL %06lu p%-3d d%-2d %-12s",
            dkwb_pool_seq++, dkwb_pool_proc, dkwb_pool_depth, ev);
}

/* Walk a {head,tail} register list and print it head-first. */
static void dkwb_list(uint8_t *mem, uint32_t list, const char *tag) {
    unsigned r, guard = 0;
    fprintf(dkwb_pool_fp, " %s=[", tag);
    r = MEM_U8(list + 0);
    while (r != DKWB_NILREG && guard++ < 80) {
        fprintf(dkwb_pool_fp, "%s%s", guard > 1 ? "," : "", dkwb_regname(r));
        r = MEM_U8(DKWB_REGTAB + 12u * r + 6);
    }
    fprintf(dkwb_pool_fp, "]");
}

static void dkwb_lists(uint8_t *mem) {
    dkwb_list(mem, DKWB_FREELIST, "free");
    dkwb_list(mem, DKWB_BUSYLIST, "busy");
}

/* usage counter + flags of one register table entry */
static void dkwb_regstate(uint8_t *mem, unsigned r) {
    if (r == DKWB_NILREG || r >= 73) return;
    fprintf(dkwb_pool_fp, " {use=%u onfree=%u kind=%u pair=%s}",
            (unsigned) MEM_U16(DKWB_REGTAB + 12u * r + 4),
            (unsigned) MEM_U8(DKWB_REGTAB + 12u * r + 7),
            (unsigned) MEM_U8(DKWB_REGTAB + 12u * r + 8),
            dkwb_regname(MEM_U8(DKWB_REGTAB + 12u * r + 9)));
}

static const char *dkwb_listname(uint32_t l) {
    if (l == DKWB_FREELIST) return "FREE";
    if (l == DKWB_BUSYLIST) return "BUSY";
    return "other";
}
"""

